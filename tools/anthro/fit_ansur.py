"""Fits the anthropometric constants in src/domain/anthropometry.ts from ANSUR II.

ANSUR II (2012 U.S. Army Anthropometric Survey) is a U.S. Government work in the
public domain. The public CSVs are hosted by the Penn State OPEN Lab:
https://www.openlab.psu.edu/ansur2/

    python3 tools/anthro/fit_ansur.py > src/domain/anthropometry.ts

Downloads are cached in tools/anthro/.cache (git-ignored) and checked by SHA-256.
All lengths are millimeters.
"""

import csv
import hashlib
import math
import pathlib
import statistics
import urllib.request

SOURCES = {
    "female": (
        "https://tools.openlab.psu.edu/publicData/ANSUR_II_FEMALE_Public.csv",
        "ed7e800aa97a4d42f8286b988be2fe1883a2e789588169db959864b707d1757a",
    ),
    "male": (
        "https://tools.openlab.psu.edu/publicData/ANSUR_II_MALE_Public.csv",
        "0547aea0170e5293de519389981135e75803f02e6d40c77ace740decc0caac64",
    ),
}

# Landmark heights the stature solve partitions the body with, top to bottom.
ALLOMETRY_COLUMNS = [
    ("headAboveTragion", "tragiontopofhead"),
    ("cervicaleHeight", "cervicaleheight"),
    ("acromialHeight", "acromialheight"),
    ("crotchHeight", "crotchheight"),
    ("kneeHeight", "kneeheightmidpatella"),
    ("lateralMalleolusHeight", "lateralmalleolusheight"),
    ("biacromialBreadth", "biacromialbreadth"),
    ("hipBreadth", "hipbreadth"),
    ("footLength", "footlength"),
]

CACHE = pathlib.Path(__file__).parent / ".cache"


def rows(sex):
    url, digest = SOURCES[sex]
    path = CACHE / url.rsplit("/", 1)[1]
    if not path.exists():
        CACHE.mkdir(exist_ok=True)
        urllib.request.urlretrieve(url, path)
    actual = hashlib.sha256(path.read_bytes()).hexdigest()
    if actual != digest:
        raise SystemExit(f"{path.name}: SHA-256 {actual} does not match {digest}")
    with path.open(encoding="latin-1") as handle:
        return list(csv.DictReader(handle))


def linear_fit(x, y):
    mean_x, mean_y = statistics.fmean(x), statistics.fmean(y)
    slope = sum((a - mean_x) * (b - mean_y) for a, b in zip(x, y)) / sum(
        (a - mean_x) ** 2 for a in x
    )
    return mean_y - slope * mean_x, slope


def percentile(values, fraction):
    ordered = sorted(values)
    return ordered[round(fraction * (len(ordered) - 1))]


def fit(sex):
    data = rows(sex)
    column = lambda name: [float(row[name]) for row in data]
    length = column("footlength")
    ball = column("balloffootlength")
    width = column("footbreadthhorizontal")
    toe = [total - heel_to_ball for total, heel_to_ball in zip(length, ball)]
    stature = column("stature")

    def ratio_band(y):
        ratios = [value / total for value, total in zip(y, length)]
        return f"{{ p01: {percentile(ratios, 0.01):.4f}, p50: {percentile(ratios, 0.5):.4f}, p99: {percentile(ratios, 0.99):.4f} }}"

    allometry = []
    log_stature = [math.log(value) for value in stature]
    for key, name in ALLOMETRY_COLUMNS:
        intercept, exponent = linear_fit(log_stature, [math.log(value) for value in column(name)])
        allometry.append(f"      {key}: {{ coefficient: {math.exp(intercept):.6g}, exponent: {exponent:.4f} }},")

    return "\n".join(
        [
            f"  {sex}: {{",
            f"    sampleSize: {len(data)},",
            f"    footLength: {{ p01: {percentile(length, 0.01):.0f}, p50: {percentile(length, 0.5):.0f}, p99: {percentile(length, 0.99):.0f} }},",
            f"    toeRatio: {ratio_band(toe)},",
            f"    widthRatio: {ratio_band(width)},",
            f"    stature: {{ p01: {percentile(stature, 0.01):.0f}, p50: {percentile(stature, 0.5):.0f}, p99: {percentile(stature, 0.99):.0f} }},",
            "    allometry: {",
            *allometry,
            "    },",
            "  },",
        ]
    )


print(
    """// Generated by tools/anthro/fit_ansur.py from the ANSUR II public data. Do not edit.
//
// Ratio bands are to foot length; they scale to any foot size, where linear fits
// with an intercept drift outside the surveyed range. Toe length is foot length
// minus ball-of-foot length (heel to first MTP joint). Allometric fits are
// value = coefficient * stature ^ exponent, in millimeters.

export type AllometricFit = { coefficient: number; exponent: number }
export type Band = { p01: number; p50: number; p99: number }

export type SexAnthropometry = {
  sampleSize: number
  footLength: Band
  toeRatio: Band
  widthRatio: Band
  stature: Band
  allometry: Record<
    | 'headAboveTragion'
    | 'cervicaleHeight'
    | 'acromialHeight'
    | 'crotchHeight'
    | 'kneeHeight'
    | 'lateralMalleolusHeight'
    | 'biacromialBreadth'
    | 'hipBreadth'
    | 'footLength',
    AllometricFit
  >
}

export const ANSUR_II: { female: SexAnthropometry; male: SexAnthropometry } = {"""
)
print(fit("female"))
print(fit("male"))
print("}")
